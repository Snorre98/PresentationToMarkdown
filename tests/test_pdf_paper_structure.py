"""Golden tests for the paper-mode paragraph and heading model (ADR-0055).

Each fixture is generated by ``tests/make_test_pdf.py`` and pins one document
class: faux-bold size tiers and wrapped bold tails (F1), uniform-size bold-only
headings (F2), a size-only hierarchy (F3), punctuation/numbered headings in
two columns with a cross-column paragraph (F4), and paragraph-model negatives
(F5). F6 pins slide mode's byte-identical legacy output.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

from converter import convert_file

TESTS_DIR = Path(__file__).parent

FAUXBOLD = TESTS_DIR / "test_paper_fauxbold.pdf"
BOLDONLY = TESTS_DIR / "test_paper_boldonly.pdf"
SIZEONLY = TESTS_DIR / "test_paper_sizeonly.pdf"
PUNCT = TESTS_DIR / "test_paper_punct_columns.pdf"
NEGATIVES = TESTS_DIR / "test_paper_negatives.pdf"
SLIDE_PDF = TESTS_DIR / "test_doc.pdf"


def _headings(text: str) -> list[tuple[int, str]]:
    headings: list[tuple[int, str]] = []
    for line in text.splitlines():
        match = re.match(r"^(#{1,6}) (.+)$", line)
        if match:
            headings.append((len(match.group(1)), match.group(2)))
    return headings


@pytest.fixture()
def paper(monkeypatch):
    """Convert a PDF in paper mode (explicit output dir: no archive side effects)."""
    monkeypatch.setenv("PDF_MODE", "paper")

    def convert(path: Path, tmp_path: Path) -> str:
        result = convert_file(path, tmp_path)
        assert result.error is None
        assert result.md_path is not None
        return result.md_path.read_text(encoding="utf-8")

    return convert


def test_fauxbold_tiers_and_wrapped_bold_tails(paper, tmp_path):
    """F1: every real heading promotes at its learned tier; wrapped bold tails
    (including one that is 40+ characters) never become headings."""
    text = paper(FAUXBOLD, tmp_path)

    assert _headings(text) == [
        (1, "Assignment 2 - Problem D"),
        (3, "Prioritizing buses for preventive maintenance"),
        (4, "Scenario"),
        (3, "3. Effect on the maintenance decision"),
        (3, "4. This heading is deliberately longer than forty characters"),
        (2, "Evidence provided"),
        (3, "6. Important limitations and uncertainties"),
        (4, "Maintenance actions influence the historical data"),
    ]
    # Wrapped bold runs merge into one balanced span, inside the paragraph.
    assert "The estimates cover approximately **10 available additional preventive inspections**." in text
    assert "The numbers should be treated as **estimates rather than guaranteed savings**." in text
    assert "A sentence that ends with **a bold run** and continues in regular text." in text
    # Mid-sentence wraps reflow into one Markdown line per paragraph.
    assert (
        "The team reviewed the fleet records and compared them with the workshop logs from last year."
        in text
    )
    # A paragraph that continues across the page boundary is one line.
    assert "The report should connect the evidence to the recommendation." in text
    # A paragraph directly after a bullet list is flush, never absorbed.
    assert "\n\nThe model relies much more strongly on these data." in text
    # No heading carries Markdown markers and nothing is continuation-indented.
    assert not any("**" in heading for _, heading in _headings(text))
    assert not any(line.startswith("  ") for line in text.splitlines())


def test_bold_only_headings_use_the_strict_ladder(paper, tmp_path):
    """F2: uniform size — a real bold heading promotes; bare bold sentences,
    wrapped bold runs and bold lead-ins stay text."""
    text = paper(BOLDONLY, tmp_path)

    assert _headings(text) == [
        (2, "A Real Section Heading"),
        (2, "Another Point:"),
    ]
    assert "**This key insight is emphasised.**" in text
    assert "The process begins with **a very important step and continues elsewhere**." in text
    assert "**Lead-in term:** the rest of the sentence follows here." in text
    assert "The paragraph continues here and then **No way this becomes a heading at all** and the text moves on." in text


def test_size_only_hierarchy_promotes_without_bold(paper, tmp_path):
    """F3: tiers alone carry the outline when the document has no bold."""
    text = paper(SIZEONLY, tmp_path)

    assert _headings(text) == [
        (1, "Size Only Study"),
        (2, "1. Introduction"),
        (3, "Data collection"),
        (3, "Data processing"),
        (2, "2. Methods in detail"),
        (2, "3. Results"),
        (3, "Measurements"),
    ]
    assert "The measurements were taken in a controlled setting." in text
    assert "**" not in text


def test_punctuated_and_numbered_headings_in_columns(paper, tmp_path):
    """F4: headings ending ``:``/``?`` promote, and a paragraph continues from
    the left column into the right one."""
    text = paper(PUNCT, tmp_path)

    assert _headings(text) == [
        (1, "Colon and Question Study"),
        (2, "1. What is measured:"),
        (2, "2. Why does it matter?"),
        (2, "3. How is it decided?"),
    ]
    assert "The recorder logs every event in the workshop." in text
    assert "The first column begins the thought and the second column completes it." in text
    assert "The question drives the design of the study." in text


def test_negative_cases_stay_text(paper, tmp_path):
    """F5: verse lines, a standalone bold sentence, a wrapped bold emphasis and
    a paragraph after a bullet list are all plain text."""
    text = paper(NEGATIVES, tmp_path)

    assert _headings(text) == []
    assert "The following lines should not become headings at all." in text
    assert "A note about **the most important consideration of all**." in text
    assert "- first bullet;\n- second bullet;" in text
    assert "\n\nThe following paragraph stands alone." in text
    assert "This line is indented like a quotation." in text
    assert "This bold sentence is not a heading." in text


def test_reflow_off_keeps_lines_but_keeps_headings(paper, tmp_path, monkeypatch):
    """``PDF_REFLOW=off`` keeps the legacy line-per-line body output while the
    paragraph model still reconstructs the headings."""
    monkeypatch.setenv("PDF_REFLOW", "off")
    text = paper(FAUXBOLD, tmp_path)

    assert _headings(text) == [
        (1, "Assignment 2 - Problem D"),
        (3, "Prioritizing buses for preventive maintenance"),
        (4, "Scenario"),
        (3, "3. Effect on the maintenance decision"),
        (3, "4. This heading is deliberately longer than forty characters"),
        (2, "Evidence provided"),
        (3, "6. Important limitations and uncertainties"),
        (4, "Maintenance actions influence the historical data"),
    ]
    assert "The team reviewed the fleet records\nand compared them with the workshop\nlogs from last year." in text
    assert "## " not in "\n".join(line for line in text.splitlines() if "**" in line)


def test_slide_mode_keeps_per_page_layout(monkeypatch, tmp_path):
    """F6: slide mode keeps one # per page, reflows body paragraphs, and
    preserves the page-break scaffold (ADR-0070)."""
    monkeypatch.delenv("PDF_MODE", raising=False)
    result = convert_file(SLIDE_PDF, tmp_path)
    assert result.error is None
    assert result.md_path is not None
    assert result.md_path.read_text(encoding="utf-8") == SLIDE_GOLDEN


